#!/usr/bin/env node
/**
 * Bundle the sensor into the one file Netlify injects (#996).
 *
 * Injected edge functions allow only inline declarations and URL imports:
 * no relative imports, no npm packages. So src/sensor/* is bundled into
 * src/edge-functions/webdecoy-sensor.ts as a single self-contained module,
 * and that file is committed. CI rebuilds it and fails on drift, so an edit
 * to the sensor that never got bundled cannot ship stale.
 *
 *   npm run build:bundle
 */
import { build } from 'esbuild';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const outDir = join(root, 'src', 'edge-functions');
const outFile = join(outDir, 'webdecoy-sensor.ts');
mkdirSync(outDir, { recursive: true });

const result = await build({
  entryPoints: [join(root, 'src', 'sensor', 'entry.ts')],
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: false,
  legalComments: 'none',
  write: false,
  logLevel: 'warning',
});
if (result.outputFiles.length !== 1) {
  console.error(`bundle: expected exactly one output, got ${result.outputFiles.length}`);
  process.exit(1);
}
const code = result.outputFiles[0].text;
if (!/export\s*\{[^}]*as default[^}]*\}|export\s+default/.test(code)) {
  console.error('bundle: output has no default export; the function would never run');
  process.exit(1);
}
if (!/export\s*\{[^}]*\bconfig\b[^}]*\}|export\s+const\s+config/.test(code)) {
  console.error('bundle: output has no config export; the function would match no path');
  process.exit(1);
}
const banner =
  '// GENERATED by edge/netlify-extension/scripts/bundle.mjs — DO NOT EDIT.\n' +
  '// Source: edge/netlify-extension/src/sensor. Rebuild with `npm run build:bundle`.\n';
writeFileSync(outFile, banner + code);
console.log(`bundle: wrote ${outFile} (${code.length} bytes)`);
